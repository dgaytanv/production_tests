#!/bin/bash
# submit_oneshot.sh — run the one-shot chain (scripts/generate.sh) as independent
# LPC HTCondor jobs, one per (particle, energy, batch). Each job runs
# run_oneshot.sh, which calls generate.sh and copies its output directory to EOS.
#
# Batch b of pdgId P at energy E (GeV) uses seed P*100000 + E*1000 + seed_offset + b
# and lands in <outdir>/<partname>_E<E>/batch<b>/ with everything generate.sh
# writes (GSD, RECO, nanoML, parquet, logs).
#
# Run from a shell without cmsenv, with a valid VOMS proxy (X509_USER_PROXY).
#
# Usage:
#   bash submit_oneshot.sh --outdir /store/user/$USER/<campaign> --workdir DIR \
#        [--particles "22:photons 211:pions 130:K0L"] \
#        [--energies "2 3 5 10 25 50 75 100 200 300"] [--nbatches 4] [--nevents 250] \
#        [--seed-offset 10] [--memory 6000] [--rebuild-tarball] [--dry-run] \
#        [-- <more generate.sh options, e.g. --gun closeBy>]
#   --workdir holds the tarball, the submit file, the job list and logs/ (not on EOS).
set -eu -o pipefail

PARTICLES="22:photons 211:pions 130:K0L"
ENERGIES="2 3 5 10 25 50 75 100 200 300"
NBATCHES=4; NEVENTS=250; SEED_OFFSET=10; MEMORY=6000
OUTDIR=""; WORKDIR=""; REBUILD_TAR=0; DRY_RUN=0; EXTRA=()

die() { echo "ERROR: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
    case "$1" in
        --particles)       PARTICLES="$2";   shift 2 ;;
        --energies)        ENERGIES="$2";    shift 2 ;;
        --nbatches)        NBATCHES="$2";    shift 2 ;;
        --nevents)         NEVENTS="$2";     shift 2 ;;
        --seed-offset)     SEED_OFFSET="$2"; shift 2 ;;
        --memory)          MEMORY="$2";      shift 2 ;;
        --outdir)          OUTDIR="$2";      shift 2 ;;
        --workdir)         WORKDIR="$2";     shift 2 ;;
        --rebuild-tarball) REBUILD_TAR=1;    shift ;;
        --dry-run)         DRY_RUN=1;        shift ;;
        --)                shift; EXTRA=("$@"); break ;;
        -h|--help)         grep '^#' "$0" | head -18; exit 0 ;;
        *)                 die "unknown arg: $1" ;;
    esac
done
case "$OUTDIR" in /store/*) ;; *) die "--outdir must be an FNAL EOS path (/store/user/...)" ;; esac
[ -n "$WORKDIR" ] || die "--workdir is required"
case "$WORKDIR" in /eos/*) die "--workdir must not be on EOS (HTCondor logs cannot live there)" ;; esac

SUBMIT_DIR="$(cd "$(dirname "$0")" && pwd)"
CMSSW_BASE_ARG="$(cd "$SUBMIT_DIR/../../.." && pwd)"
CMSSW_NAME="$(basename "$CMSSW_BASE_ARG")"
[ -d "$CMSSW_BASE_ARG/src" ] && [ -d "$CMSSW_BASE_ARG/lib" ] \
    || die "$CMSSW_BASE_ARG does not look like a CMSSW area (this repo must sit in \$CMSSW_BASE/src)"
mkdir -p "$WORKDIR/logs"
WORKDIR="$(cd "$WORKDIR" && pwd)"
TAG="$(basename "$OUTDIR")"

# ---- proxy ------------------------------------------------------------------------
[ -n "${X509_USER_PROXY:-}" ] && [ -f "$X509_USER_PROXY" ] \
    || die "X509_USER_PROXY not set or missing; run: voms-proxy-init -voms cms -valid 192:00"
[ "$(voms-proxy-info -timeleft 2>/dev/null || echo 0)" -gt 3600 ] \
    || die "the VOMS proxy expires within an hour; run: voms-proxy-init -voms cms -valid 192:00"

# ---- tarball (same content as the one submit_dag.sh builds) -------------------------
TARBALL="$WORKDIR/${CMSSW_NAME}.tar.gz"
if [ "$REBUILD_TAR" -eq 1 ] || [ ! -f "$TARBALL" ]; then
    echo "Building tarball $TARBALL ..."
    ( cd "$(dirname "$CMSSW_BASE_ARG")" && \
      tar --exclude="${CMSSW_NAME}/tmp" \
          --exclude="${CMSSW_NAME}/logs" \
          --exclude="${CMSSW_NAME}/src/production_tests/condor" \
          --exclude="${CMSSW_NAME}/src/production_tests/parquet_out" \
          --exclude="${CMSSW_NAME}/src/production_tests/test*.root" \
          --exclude="${CMSSW_NAME}/src/production_tests/smoke*.root" \
          --exclude=".git" \
          -czf "$TARBALL" "${CMSSW_NAME}" )
fi
echo "Tarball: $TARBALL ($(du -h "$TARBALL" | cut -f1), built $(date -r "$TARBALL" '+%F %T'))"

# ---- job list: eosdir nevents pdg name energy batch seed -----------------------------
JOBS="$WORKDIR/${TAG}_jobs.txt"
: > "$JOBS"
for spec in $PARTICLES; do
    pdg="${spec%%:*}"; name="${spec#*:}"
    for e in $ENERGIES; do
        for ((b = 0; b < NBATCHES; b++)); do
            echo "${OUTDIR}/${name}_E${e}/batch${b} ${NEVENTS} ${pdg} ${name} ${e} ${b}" \
                 "$(( pdg * 100000 + e * 1000 + SEED_OFFSET + b ))" >> "$JOBS"
        done
    done
done

# ---- submit file -------------------------------------------------------------------
JDL="$WORKDIR/${TAG}.jdl"
cat > "$JDL" <<EOF
# Auto-generated by submit_oneshot.sh: scripts/generate.sh, one job per batch
universe                = vanilla
executable              = ${SUBMIT_DIR}/run_oneshot.sh
arguments               = \$(eosdir) \$(nevents) --particle \$(pdg) --partname \$(name) --minE \$(energy) --maxE \$(energy) --seed \$(seed) ${EXTRA[*]:-}
should_transfer_files   = YES
when_to_transfer_output = ON_EXIT
transfer_output_files   = ""
transfer_input_files    = ${TARBALL}
output                  = logs/${TAG}_\$(name)_E\$(energy)_batch\$(batch).out
error                   = logs/${TAG}_\$(name)_E\$(energy)_batch\$(batch).err
log                     = logs/${TAG}.log
request_cpus            = 1
request_memory          = ${MEMORY}
request_disk            = 20000000
+MaxRuntime             = 86400
+DesiredOS              = "rhel9"
+REQUIRED_OS            = "rhel9"
x509userproxy           = \$ENV(X509_USER_PROXY)
queue eosdir,nevents,pdg,name,energy,batch,seed from ${JOBS}
EOF

echo "Jobs: $(wc -l < "$JOBS") = particles [$PARTICLES] x energies [$ENERGIES] x $NBATCHES batches, $NEVENTS events each"
echo "Output: ${OUTDIR}/<partname>_E<E>/batch<b>/   extra generate.sh options: ${EXTRA[*]:-none}"
if [ "$DRY_RUN" -eq 1 ]; then
    echo "Dry run, not submitting. Submit file: $JDL   job list: $JOBS"
    exit 0
fi
cd "$WORKDIR"
env -u PYTHONHOME -u PYTHONPATH -u LD_LIBRARY_PATH condor_submit "$JDL"
